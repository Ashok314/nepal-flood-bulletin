export function getTweetRescued(): Person[] {
  return RAW.trim()
    .split("\n")
    .filter(Boolean)
    .map((line, i) => {
      const [name, age, place, sex] = line.split("|");
      return {
        id: `tweet-${i + 1}`,
        name: name.trim(),
        age: age && age.trim() !== "-" ? age.trim() : undefined,
        place: place?.trim() || undefined,
        note: sex?.trim() === "F" ? "महिला" : "पुरुष",
        country: "Nepal",
        rescueStatus: "Rescued",
        source: SOURCE,
        status: "found" as const,
      };
    });
}
